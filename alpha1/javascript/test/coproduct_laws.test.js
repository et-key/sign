//   取る関数が点なしなら G10 で比べの外、`5 inc [* 2]` は Q23 の答えで通し、作り直しの最初の版は `(5 inc) [* 2]` で G10）。主語の口が
//   決まらない逆適用（`5 add`・`5 [<<]`、§5 Q5）は、後ろに実引数が来なければ行の終わりで `_`（R42）で、前から書いた `add … 5` の足りない
