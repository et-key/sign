	if (o.crash) return { text: `例外 ${o.crash}` };
	if (o.refused) return { text: `断り ${refusalText(o)}`, refused: true };
	if (o.trees.length !== units.length) return { text: `木の数 ${o.trees.length} が文の数 ${units.length} と違う` };
